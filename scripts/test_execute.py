class TestInvokeCodex:
    @staticmethod
    def successful_stream():
        return "\n".join(json.dumps(event) for event in [
            {"type": "thread.started", "thread_id": "thread-test"},
            {"type": "item.completed", "item": {"type": "agent_message", "text": "작업 완료"}},
            {"type": "turn.completed", "usage": {"input_tokens": 120, "output_tokens": 30}},
        ])

    def test_runs_codex_with_stdin_and_workspace_sandbox(self, executor):
        result = MagicMock(returncode=0, stdout=self.successful_stream(), stderr="")
        with patch("subprocess.run", return_value=result) as run:
            executor._invoke_codex({"step": 2, "name": "ui"}, "PREAMBLE\n")
        command = run.call_args.args[0]
        assert command[0] == "codex"
        assert "exec" in command and "--json" in command
        assert command[command.index("--sandbox") + 1] == "workspace-write"
        assert command[command.index("--ask-for-approval") + 1] == "never"
        assert not any(arg.startswith("--dangerously-") for arg in command)
        assert command[-1] == "-"
        assert "PREAMBLE" in run.call_args.kwargs["input"]
        assert "UI를 구현하세요" in run.call_args.kwargs["input"]
        assert run.call_args.kwargs["cwd"] == executor._root
        assert run.call_args.kwargs["timeout"] == 1800

    def test_saves_events_message_and_token_usage(self, executor):
        result = MagicMock(returncode=0, stdout=self.successful_stream(), stderr="")
        with patch("subprocess.run", return_value=result):
            executor._invoke_codex({"step": 2, "name": "ui"}, "preamble")
        data = json.loads((executor._phase_dir / "step2-output.json").read_text())
        assert data["step"] == 2 and data["exitCode"] == 0
        assert data["turnCompleted"] is True
        assert data["message"] == "작업 완료"
        assert data["usage"]["input_tokens"] == 120
        assert len(data["events"]) == 3

    def test_failed_turn_is_reported_even_with_zero_exit(self, executor):
        stream = json.dumps({"type": "turn.failed", "error": {"message": "rate limit"}})
        with patch("subprocess.run", return_value=MagicMock(returncode=0, stdout=stream, stderr="")):
            data = executor._invoke_codex({"step": 2, "name": "ui"}, "")
        assert data["turnCompleted"] is False
        assert "rate limit" in data["error"]

    @pytest.mark.parametrize("stream", ["not json", "[]", '{"type":"thread.started"}'])
    def test_incomplete_output_is_not_success(self, executor, stream):
        with patch("subprocess.run", return_value=MagicMock(returncode=0, stdout=stream, stderr="")):
            data = executor._invoke_codex({"step": 2, "name": "ui"}, "")
        assert data["turnCompleted"] is False
        assert data["error"]

    def test_timeout_is_saved_for_retry(self, executor):
        failure = subprocess.TimeoutExpired("codex", 1800, output=b'{"type":"turn.started"}', stderr=b"slow")
        with patch("subprocess.run", side_effect=failure):
            data = executor._invoke_codex({"step": 2, "name": "ui"}, "")
        assert data["exitCode"] == 124
        assert data["timedOut"] is True
        assert "1800" in data["error"]
        assert (executor._phase_dir / "step2-output.json").exists()

    def test_nonexistent_step_file_exits(self, executor):
        with pytest.raises(SystemExit) as error:
            executor._invoke_codex({"step": 99, "name": "missing"}, "")
        assert error.value.code == 1

    @pytest.mark.parametrize("exit_code", [0, 1])
    def test_failed_run_cannot_accept_agent_completed_status(self, executor, exit_code):
        def invoke(step, preamble):
            index = executor._read_json(executor._index_file)
            index["steps"][2].update(status="completed", summary="claimed complete")
            executor._write_json(executor._index_file, index)
